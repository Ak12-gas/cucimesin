CREATE TABLE IF NOT EXISTS mitra (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, nama_showroom VARCHAR(150) NOT NULL, alamat TEXT,
  telepon VARCHAR(40), email VARCHAR(191), pic_nama VARCHAR(150), pic_telepon VARCHAR(40),
  diskon_persen DECIMAL(5,2) NOT NULL DEFAULT 15, logo VARCHAR(255),
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (id), UNIQUE KEY uq_mitra_email (email)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, nama VARCHAR(150) NOT NULL, email VARCHAR(191) UNIQUE,
  telepon VARCHAR(40) UNIQUE, password VARCHAR(255) NOT NULL,
  role ENUM('admin','teknisi','pelanggan','mitra') NOT NULL, mitra_id INT UNSIGNED,
  aktif TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id), KEY idx_users_role (role), FOREIGN KEY (mitra_id) REFERENCES mitra(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pelanggan (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, user_id INT UNSIGNED UNIQUE, nama VARCHAR(150) NOT NULL,
  telepon VARCHAR(40), email VARCHAR(191), alamat TEXT, kategori ENUM('Normal','B2B') NOT NULL DEFAULT 'Normal',
  mitra_id INT UNSIGNED, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (id),
  KEY idx_pelanggan_telepon (telepon), FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  FOREIGN KEY (mitra_id) REFERENCES mitra(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS layanan (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, nama VARCHAR(150) NOT NULL, harga INT NOT NULL,
  durasi_menit INT NOT NULL DEFAULT 45, deskripsi TEXT, aktif TINYINT(1) NOT NULL DEFAULT 1, PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS spk (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, no_spk VARCHAR(50) NOT NULL UNIQUE, pelanggan_id INT UNSIGNED,
  mitra_id INT UNSIGNED, plat_nomor VARCHAR(30) NOT NULL, merk_tipe VARCHAR(150), tahun VARCHAR(10),
  warna VARCHAR(50), layanan_id INT UNSIGNED, harga INT, diskon INT NOT NULL DEFAULT 0, total INT,
  teknisi_id INT UNSIGNED, status ENUM('Menunggu','Dikerjakan','Selesai','Batal') NOT NULL DEFAULT 'Menunggu',
  catatan TEXT, waktu_mulai DATETIME, waktu_selesai DATETIME, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id), KEY idx_spk_status (status), KEY idx_spk_teknisi (teknisi_id),
  FOREIGN KEY (pelanggan_id) REFERENCES pelanggan(id) ON DELETE SET NULL, FOREIGN KEY (mitra_id) REFERENCES mitra(id) ON DELETE SET NULL,
  FOREIGN KEY (layanan_id) REFERENCES layanan(id) ON DELETE SET NULL, FOREIGN KEY (teknisi_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS spk_checklist (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, spk_id INT UNSIGNED NOT NULL, item VARCHAR(255) NOT NULL,
  selesai TINYINT(1) NOT NULL DEFAULT 0, urutan INT NOT NULL DEFAULT 0, PRIMARY KEY (id), KEY idx_checklist_spk (spk_id),
  FOREIGN KEY (spk_id) REFERENCES spk(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS spk_foto (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, spk_id INT UNSIGNED NOT NULL, tipe ENUM('sebelum','sesudah') NOT NULL,
  path VARCHAR(255) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (id),
  FOREIGN KEY (spk_id) REFERENCES spk(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS spk_laporan (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, spk_id INT UNSIGNED NOT NULL, teknisi_id INT UNSIGNED,
  laporan TEXT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id), UNIQUE KEY uq_spk_laporan_spk (spk_id),
  FOREIGN KEY (spk_id) REFERENCES spk(id) ON DELETE CASCADE,
  FOREIGN KEY (teknisi_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS transaksi (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, tipe ENUM('masuk','keluar') NOT NULL, kategori VARCHAR(100),
  deskripsi TEXT, nominal INT NOT NULL, spk_id INT UNSIGNED, mitra_id INT UNSIGNED,
  tanggal DATE NOT NULL DEFAULT (CURRENT_DATE), created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id), KEY idx_trx_tanggal (tanggal), FOREIGN KEY (spk_id) REFERENCES spk(id) ON DELETE SET NULL,
  FOREIGN KEY (mitra_id) REFERENCES mitra(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pembayaran (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, spk_id INT UNSIGNED NOT NULL,
  nominal INT UNSIGNED NOT NULL, metode VARCHAR(40) NOT NULL DEFAULT 'Transfer Bank',
  bukti_path VARCHAR(255), status ENUM('Menunggu Konfirmasi','Dikonfirmasi','Ditolak') NOT NULL DEFAULT 'Menunggu Konfirmasi',
  catatan_admin VARCHAR(500), submitted_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  confirmed_at DATETIME, confirmed_by INT UNSIGNED, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id), UNIQUE KEY uq_pembayaran_spk (spk_id), KEY idx_pembayaran_status (status),
  FOREIGN KEY (spk_id) REFERENCES spk(id) ON DELETE CASCADE,
  FOREIGN KEY (confirmed_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS invoice_mitra (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, no_invoice VARCHAR(70) NOT NULL UNIQUE, mitra_id INT UNSIGNED NOT NULL,
  periode_mulai DATE, periode_selesai DATE, total_unit INT NOT NULL DEFAULT 0, subtotal INT NOT NULL DEFAULT 0,
  diskon INT NOT NULL DEFAULT 0, total INT NOT NULL DEFAULT 0, status ENUM('Belum Dibayar','Lunas') NOT NULL DEFAULT 'Belum Dibayar',
  jatuh_tempo DATE, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (id),
  FOREIGN KEY (mitra_id) REFERENCES mitra(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS invoice_mitra_spk (
  invoice_id INT UNSIGNED NOT NULL, spk_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (invoice_id, spk_id), UNIQUE KEY uq_invoice_mitra_spk_spk (spk_id),
  FOREIGN KEY (invoice_id) REFERENCES invoice_mitra(id) ON DELETE CASCADE,
  FOREIGN KEY (spk_id) REFERENCES spk(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS booking (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, user_id INT UNSIGNED, nama VARCHAR(150) NOT NULL, telepon VARCHAR(40) NOT NULL,
  email VARCHAR(191), plat_nomor VARCHAR(30) NOT NULL, merk_tipe VARCHAR(150), layanan_id INT UNSIGNED,
  tanggal DATE, waktu TIME, catatan TEXT, status ENUM('Baru','Diproses','Dikonversi','Batal') NOT NULL DEFAULT 'Baru',
  spk_id INT UNSIGNED, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (id),
  KEY idx_booking_user (user_id),
  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL,
  FOREIGN KEY (layanan_id) REFERENCES layanan(id) ON DELETE SET NULL, FOREIGN KEY (spk_id) REFERENCES spk(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS pengaturan (`key` VARCHAR(100) NOT NULL, `value` TEXT, PRIMARY KEY (`key`)) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE IF NOT EXISTS audit_log (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, entity_type VARCHAR(100) NOT NULL, entity_id INT UNSIGNED,
  action VARCHAR(100) NOT NULL, actor_id INT UNSIGNED, actor_role VARCHAR(30), detail JSON,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (id), FOREIGN KEY (actor_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS armada (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, mitra_id INT UNSIGNED NOT NULL,
  plat_nomor VARCHAR(30) NOT NULL, merk_tipe VARCHAR(150), tahun VARCHAR(10), warna VARCHAR(50),
  aktif TINYINT(1) NOT NULL DEFAULT 1, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id), UNIQUE KEY uq_armada_mitra_plat (mitra_id, plat_nomor), KEY idx_armada_mitra (mitra_id),
  FOREIGN KEY (mitra_id) REFERENCES mitra(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS booking_armada (
  id INT UNSIGNED NOT NULL AUTO_INCREMENT, mitra_id INT UNSIGNED NOT NULL, layanan_id INT UNSIGNED NOT NULL,
  tanggal DATE NOT NULL, waktu TIME NOT NULL, catatan TEXT,
  status ENUM('Baru','Diproses','Dikonversi','Batal') NOT NULL DEFAULT 'Baru',
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY (id),
  KEY idx_booking_armada_mitra (mitra_id), KEY idx_booking_armada_schedule (tanggal, waktu),
  FOREIGN KEY (mitra_id) REFERENCES mitra(id) ON DELETE CASCADE,
  FOREIGN KEY (layanan_id) REFERENCES layanan(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS booking_armada_unit (
  booking_id INT UNSIGNED NOT NULL, armada_id INT UNSIGNED NOT NULL,
  PRIMARY KEY (booking_id, armada_id),
  FOREIGN KEY (booking_id) REFERENCES booking_armada(id) ON DELETE CASCADE,
  FOREIGN KEY (armada_id) REFERENCES armada(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;