CREATE TABLE IF NOT EXISTS mitra (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama_showroom VARCHAR(150) NOT NULL,
  alamat TEXT,
  telepon VARCHAR(40),
  email VARCHAR(191),
  pic_nama VARCHAR(150),
  pic_telepon VARCHAR(40),
  diskon_persen DECIMAL(5,2) NOT NULL DEFAULT 15,
  logo VARCHAR(255),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_mitra_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(150) NOT NULL,
  email VARCHAR(191) UNIQUE,
  telepon VARCHAR(40) UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL CHECK (role IN ('admin','teknisi','pelanggan','mitra')),
  mitra_id INTEGER REFERENCES mitra(id) ON DELETE SET NULL,
  aktif SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);

CREATE TABLE IF NOT EXISTS pelanggan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER UNIQUE REFERENCES users(id) ON DELETE SET NULL,
  nama VARCHAR(150) NOT NULL,
  telepon VARCHAR(40),
  email VARCHAR(191),
  alamat TEXT,
  kategori VARCHAR(20) NOT NULL DEFAULT 'Normal' CHECK (kategori IN ('Normal','B2B')),
  mitra_id INTEGER REFERENCES mitra(id) ON DELETE SET NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pelanggan_telepon ON pelanggan(telepon);

CREATE TABLE IF NOT EXISTS layanan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nama VARCHAR(150) NOT NULL,
  harga INTEGER NOT NULL,
  durasi_menit INTEGER NOT NULL DEFAULT 45,
  deskripsi TEXT,
  aktif SMALLINT NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS spk (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  no_spk VARCHAR(50) NOT NULL UNIQUE,
  pelanggan_id INTEGER REFERENCES pelanggan(id) ON DELETE SET NULL,
  mitra_id INTEGER REFERENCES mitra(id) ON DELETE SET NULL,
  plat_nomor VARCHAR(30) NOT NULL,
  merk_tipe VARCHAR(150),
  tahun VARCHAR(10),
  warna VARCHAR(50),
  layanan_id INTEGER REFERENCES layanan(id) ON DELETE SET NULL,
  harga INTEGER,
  diskon INTEGER NOT NULL DEFAULT 0,
  total INTEGER,
  teknisi_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Menunggu' CHECK (status IN ('Menunggu','Dikerjakan','Selesai','Batal')),
  catatan TEXT,
  waktu_mulai TIMESTAMP,
  waktu_selesai TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_spk_status ON spk(status);
CREATE INDEX IF NOT EXISTS idx_spk_teknisi ON spk(teknisi_id);

CREATE TABLE IF NOT EXISTS spk_checklist (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spk_id INTEGER NOT NULL REFERENCES spk(id) ON DELETE CASCADE,
  item VARCHAR(255) NOT NULL,
  selesai SMALLINT NOT NULL DEFAULT 0,
  urutan INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS idx_checklist_spk ON spk_checklist(spk_id);

CREATE TABLE IF NOT EXISTS spk_foto (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spk_id INTEGER NOT NULL REFERENCES spk(id) ON DELETE CASCADE,
  tipe VARCHAR(20) NOT NULL CHECK (tipe IN ('sebelum','sesudah')),
  path VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS spk_laporan (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spk_id INTEGER NOT NULL UNIQUE REFERENCES spk(id) ON DELETE CASCADE,
  teknisi_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  laporan TEXT NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS transaksi (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipe VARCHAR(10) NOT NULL CHECK (tipe IN ('masuk','keluar')),
  kategori VARCHAR(100),
  deskripsi TEXT,
  nominal INTEGER NOT NULL,
  spk_id INTEGER REFERENCES spk(id) ON DELETE SET NULL,
  mitra_id INTEGER REFERENCES mitra(id) ON DELETE SET NULL,
  tanggal DATE NOT NULL DEFAULT CURRENT_DATE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_trx_tanggal ON transaksi(tanggal);

CREATE TABLE IF NOT EXISTS pembayaran (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  spk_id INTEGER NOT NULL UNIQUE REFERENCES spk(id) ON DELETE CASCADE,
  nominal INTEGER NOT NULL,
  metode VARCHAR(40) NOT NULL DEFAULT 'Transfer Bank',
  bukti_path VARCHAR(255),
  status VARCHAR(30) NOT NULL DEFAULT 'Menunggu Konfirmasi'
    CHECK (status IN ('Menunggu Konfirmasi','Dikonfirmasi','Ditolak')),
  catatan_admin VARCHAR(500),
  submitted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  confirmed_at TIMESTAMP,
  confirmed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_pembayaran_status ON pembayaran(status);

CREATE TABLE IF NOT EXISTS invoice_mitra (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  no_invoice VARCHAR(70) NOT NULL UNIQUE,
  mitra_id INTEGER NOT NULL REFERENCES mitra(id) ON DELETE CASCADE,
  periode_mulai DATE,
  periode_selesai DATE,
  total_unit INTEGER NOT NULL DEFAULT 0,
  subtotal INTEGER NOT NULL DEFAULT 0,
  diskon INTEGER NOT NULL DEFAULT 0,
  total INTEGER NOT NULL DEFAULT 0,
  status VARCHAR(20) NOT NULL DEFAULT 'Belum Dibayar' CHECK (status IN ('Belum Dibayar','Lunas')),
  jatuh_tempo DATE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS invoice_mitra_spk (
  invoice_id INTEGER NOT NULL REFERENCES invoice_mitra(id) ON DELETE CASCADE,
  spk_id INTEGER NOT NULL UNIQUE REFERENCES spk(id) ON DELETE RESTRICT,
  PRIMARY KEY (invoice_id, spk_id)
);

CREATE TABLE IF NOT EXISTS booking (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  nama VARCHAR(150) NOT NULL,
  telepon VARCHAR(40) NOT NULL,
  email VARCHAR(191),
  plat_nomor VARCHAR(30) NOT NULL,
  merk_tipe VARCHAR(150),
  layanan_id INTEGER REFERENCES layanan(id) ON DELETE SET NULL,
  tanggal DATE,
  waktu TIME,
  catatan TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'Baru' CHECK (status IN ('Baru','Diproses','Dikonversi','Batal')),
  spk_id INTEGER REFERENCES spk(id) ON DELETE SET NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_booking_user ON booking(user_id);
CREATE INDEX IF NOT EXISTS idx_booking_schedule ON booking(tanggal, waktu, status);

CREATE TABLE IF NOT EXISTS booking_schedule_lock (
  tanggal DATE PRIMARY KEY
);

CREATE TABLE IF NOT EXISTS pengaturan (
  "key" VARCHAR(100) PRIMARY KEY,
  "value" TEXT
);

CREATE TABLE IF NOT EXISTS audit_log (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_type VARCHAR(100) NOT NULL,
  entity_id INTEGER,
  action VARCHAR(100) NOT NULL,
  actor_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
  actor_role VARCHAR(30),
  detail JSONB,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS armada (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mitra_id INTEGER NOT NULL REFERENCES mitra(id) ON DELETE CASCADE,
  plat_nomor VARCHAR(30) NOT NULL,
  merk_tipe VARCHAR(150),
  tahun VARCHAR(10),
  warna VARCHAR(50),
  aktif SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_armada_mitra_plat UNIQUE (mitra_id, plat_nomor)
);
CREATE INDEX IF NOT EXISTS idx_armada_mitra ON armada(mitra_id);

CREATE TABLE IF NOT EXISTS booking_armada (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mitra_id INTEGER NOT NULL REFERENCES mitra(id) ON DELETE CASCADE,
  layanan_id INTEGER NOT NULL REFERENCES layanan(id) ON DELETE RESTRICT,
  tanggal DATE NOT NULL,
  waktu TIME NOT NULL,
  catatan TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'Baru' CHECK (status IN ('Baru','Diproses','Dikonversi','Batal')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_booking_armada_mitra ON booking_armada(mitra_id);
CREATE INDEX IF NOT EXISTS idx_booking_armada_schedule ON booking_armada(tanggal, waktu);

CREATE TABLE IF NOT EXISTS booking_armada_unit (
  booking_id INTEGER NOT NULL REFERENCES booking_armada(id) ON DELETE CASCADE,
  armada_id INTEGER NOT NULL REFERENCES armada(id) ON DELETE CASCADE,
  PRIMARY KEY (booking_id, armada_id)
);
